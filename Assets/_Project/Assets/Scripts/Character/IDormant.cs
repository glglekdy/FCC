// 깨우기 전까지 제자리에 선 채 플레이어를 무시하는 대기(잠듦) 상태를 받을 수 있는 몬스터 AI 컴포넌트가 구현한다.
// 던전 전투방이 몬스터를 앞 방에서 미리 세워 보여 줄 때 쓴다(DungeonRoomSpawner.SpawnDormant).
//
// 스포너가 컴포넌트를 통째로 꺼 버리지 않고 이 인터페이스로 묻는 이유는, 끄면 걷기 모션 값 · 미끄러지던 속도 ·
// 이벤트 구독이 꺼진 순간 그대로 굳기 때문이다. 멈춰 서는 방법은 구속(IRestrainable)처럼 몬스터마다 달라서 각자 맡는다.
// **새 몬스터 AI를 만들면 이것도 구현하세요.** 구현하지 않은 몬스터는 미리 보이는 동안에도 순찰 · 추격 · 공격을 한다.
public interface IDormant {
    // true 면 제자리에서 기다리고, false 면 평소 AI로 돌아간다. 대기 중에도 피해 · 넉백은 그대로 받는다.
    void SetDormant(bool dormant);
}
